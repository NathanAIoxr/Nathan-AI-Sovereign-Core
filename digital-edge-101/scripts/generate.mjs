import fs from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("../", import.meta.url));
const read = file => fs.readFile(path.join(root, file), "utf8");
const write = (file, data) => fs.writeFile(path.join(root, file), data);
const definitions = new Map();
const wrappers = [];
const groups = (await fs.readdir(path.join(root, "packages"))).sort();
for (const directory of ["kernel", ...groups.map(x => "packages/" + x)]) {
  const sourceFile = directory + (directory === "kernel" ? "/algorithms.ts" : "/src/algorithms.ts");
  const { modules } = await import(new URL("../" + sourceFile, import.meta.url));
  const dest = directory + "/src";
  await fs.mkdir(path.join(root, dest), { recursive:true });
  for (const [id, impl] of Object.entries(modules)) {
    if (definitions.has(id)) throw Error("Duplicate module " + id);
    definitions.set(id, { ...impl, group: directory.split("/").at(-1) });
    const entry = dest + "/mod_" + id.replaceAll("-", "_") + ".ts";
    const importPath = directory === "kernel" ? "../algorithms.ts" : "./algorithms.ts";
    await write(entry, '// Generated by scripts/generate.mjs.\nimport { modules } from "' + importPath + '";\nexport const { execute, sample, title } = modules[' + JSON.stringify(id) + '];\n');
    wrappers.push([id, entry]);
  }
}
const entries = new Map();
const extension = JSON.parse(await read("schemas/extension-spec.json"));
let extensionIndex=203;
for (const [group,titles] of Object.entries(extension)) for(const title of titles)entries.set(String(extensionIndex++),{title,group});
if(extensionIndex!==304)throw Error("Extension registry must cover 203–303");
const timeline = (await read("schemas/og-timeline.txt")).trim().split("\n").map(line=>line.split("|"));
if(timeline.length!==101 || new Set(timeline.map(x=>x[0])).size!==101)throw Error("Invalid OG timeline");
for(const [id,date,title] of timeline)entries.set("OG-"+id,{title,date,group:"kernel"});
const inRange = (n,a,b)=>n>=a&&n<=b;
function ring(id) {
  if(id.startsWith("OG-"))return 0;
  const n=Number(id);
  if(inRange(n,1,15)||inRange(n,162,176)||[228,268,271,289,301].includes(n))return 1;
  if(inRange(n,16,30)||inRange(n,102,116)||inRange(n,203,217)||inRange(n,304,318)||inRange(n,263,277))return 2;
  if(inRange(n,278,303)||inRange(n,389,404)||inRange(n,177,202))return 3;
  if(inRange(n,117,161)||inRange(n,218,262)||inRange(n,319,378))return 4;
  return inRange(n,61,75)||inRange(n,379,388)?3:2;
}
const ids=[...Array.from({length:404},(_,i)=>String(i+1).padStart(3,"0")),...timeline.map(row=>"OG-"+row[0])];
const table=ids.map(id=>{
  const impl=definitions.get(id), spec=entries.get(id);
  const status=impl?(id.startsWith("OG-")||Number(id)>=203?"fixture":"executable"):(spec?"specified":"awaiting-spec");
  return {id, ring:ring(id), category:spec?.group??impl?.group??"unassigned", title:spec?.title??impl?.title??null,
    ...(spec?.date?{submittedDate:spec.date}:{}),status, ...(impl?{implementation:impl.title, effect:"read-only",
      request:"JSON object; binary modules also accept an ArrayBuffer in the TypeScript interface",
      output:"JSON result",bindings:id==="071"?["GRAPH"]:id==="091"?["Rust WebAssembly"]:[],
      endpoint:"/api/modules/"+id, syscall:"/syscall", sample:impl.sample}: {})};
});
await write("registry/os-syscall-table.json",JSON.stringify(table,null,2)+"\n");
await write("schemas/module-manifest.json",JSON.stringify(table,null,2)+"\n");
await write("registry/handlers.ts",wrappers.map(([id,file],i)=>'import * as m'+i+' from "../'+file+'";').join("\n")
  +"\nexport const handlers = new Map(["+wrappers.map(([id],i)=>"["+JSON.stringify(id)+",m"+i+"]").join(",")+"]);\n");
console.log("Generated "+table.length+" registry entries and "+wrappers.length+" executable handlers");
