import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

const work = mkdtempSync(join(tmpdir(), "llmagi-boot-"));
const local = file => fileURLToPath(new URL(file, import.meta.url));
const modulePath = local("../../../deployments/conductor/handoffs/llmagi-native-image.mjs");
try {
  const assemble = (name, address) => {
    const object = join(work, name + ".o");
    const binary = join(work, name + ".bin");
    execFileSync("as", ["--32", "-o", object, local(name + ".S")]);
    execFileSync("ld", ["-m", "elf_i386", "-Ttext", address, "--oformat", "binary", "-o", binary, object]);
    return readFileSync(binary);
  };
  const boot = assemble("boot", "0x7c00");
  const kernel = assemble("kernel", "0x8000");
  if (boot.length !== 512 || boot.readUInt16LE(510) !== 0xaa55 || kernel.length > 2048) {
    throw new Error("Unexpected boot geometry.");
  }
  const sectors = Buffer.concat([boot, kernel]);
  const image = Buffer.alloc(1_474_560);
  sectors.copy(image);
  const sha256 = createHash("sha256").update(image).digest("hex");
  const release = "// Generated by standalone-apps/nutcracker-bedroom-trinity/native/build.mjs\n" +
    `export const nativeImage = ${JSON.stringify({ sha256, size: image.length, base64: sectors.toString("base64") })};\n`;
  if (process.argv.includes("--module")) writeFileSync(modulePath, release);
  if (process.argv.includes("--check-module") && readFileSync(modulePath, "utf8") !== release) {
    throw new Error("The served release does not match the assembled image.");
  }
  const output = process.argv.slice(2).find(arg => !arg.startsWith("--"));
  if (output) writeFileSync(output, image);
  console.log("LLMAGI boot image SHA-256 " + sha256);
} finally {
  rmSync(work, { force: true, recursive: true });
}
