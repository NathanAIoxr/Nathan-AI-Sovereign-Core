import { readFileSync } from 'node:fs';
import { pathToFileURL } from 'node:url';

const read = (path) => readFileSync(new URL(path, import.meta.url), 'utf8');
export const catalog = JSON.parse(read('./catalog.json'));
export const schema = read('./coins_schema.sql');

const columns = ['id', 'symbol', 'name', 'index_group', 'consensus_or_math', 'asset_class', 'notes',
  'submitted', 'submitted_seed', 'source_url', 'related_id', 'position', 'design_units'];
const quote = (value) => {
  if (value === null) return 'NULL';
  if (typeof value === 'number' && Number.isSafeInteger(value)) return String(value);
  const text = typeof value === 'string' ? value : JSON.stringify(value);
  return "'" + text.replaceAll("'", "''") + "'";
};
export const seed = [
  '-- Generated by build.mjs from catalog.json.',
  ...Array.from({ length: Math.ceil(catalog.length / 50) }, (_, index) => {
    const rows = catalog.slice(index * 50, (index + 1) * 50);
    return [
      'INSERT INTO sovereign_coins (' + columns.join(', ') + ') VALUES',
      rows.map((row) => '(' + columns.map((column) => quote(row[column])).join(', ') + ')').join(',\n'),
      'ON CONFLICT(id) DO UPDATE SET ' + columns.slice(1).map((column) => column + ' = excluded.' + column).join(', ') + ';',
    ].join('\n');
  }),
].join('\n') + '\n';

export function masterDeploy() {
  const bounties = ['schema.sql', 'seed.sql'].map((name) => read('../../global-bounties/' + name).trim());
  return ['-- Clean-database import of the coin registry and source-backed bounty catalog.',
    schema.trim(), seed.trim(), ...bounties].join('\n\n') + '\n';
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const command = process.argv[2];
  if (command === 'seed') process.stdout.write(seed);
  else if (command === 'master') process.stdout.write(masterDeploy());
  else throw new Error('Choose seed or master.');
}
