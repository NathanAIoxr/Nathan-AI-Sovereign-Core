import { readFile, writeFile, mkdir } from "node:fs/promises";

const read = (name) => readFile(new URL(name, import.meta.url), "utf8");
const [worker, schema, data, openapi, civicData] = await Promise.all(
  ["worker.js", "schema.sql", "catalog.json", "openapi.json", "civic-work.json"].map(read)
);
const { checked_on, groups } = JSON.parse(data);
const civicWork = JSON.parse(civicData);
const sourceItems = civicWork.records.map(({ source_item }) => source_item);
if (sourceItems.length !== 101 || sourceItems.some((item, index) => item !== index + 1) ||
    new Set(civicWork.records.map(({ id }) => id)).size !== sourceItems.length ||
    civicWork.records.some(({ category }) => !Object.hasOwn(civicWork.categories, category))) {
  throw new Error("Civic issue register must preserve source items 1–101 exactly once");
}
const intakeItems = civicWork.prize_intake.flatMap(({ source_items, count }) => {
  const items = source_items.flatMap((span) => {
    const [first, last = first] = span.split("–").map(Number);
    return Array.from({ length: last - first + 1 }, (_, index) => first + index);
  });
  if (items.length !== count) throw new Error("Prize intake count differs from its source item range");
  return items;
}).sort((a, b) => a - b);
if (intakeItems.length !== sourceItems.length || intakeItems.some((item, index) => item !== sourceItems[index])) {
  throw new Error("Prize intake must account for source items 1–101 exactly once");
}
const columns = [
  "id", "title", "organization", "category", "payout_usd", "payout_kind",
  "status", "deadline", "source_url", "description", "checked_on"
];
const rows = groups.flatMap(({ entries, ...group }) =>
  entries.map(([id, title, description]) => ({ ...group, id, title, description, checked_on }))
);
if (new Set(rows.map(({ id }) => id)).size !== rows.length) {
  throw new Error("Catalog contains duplicate record IDs");
}

function sqlValue(value) {
  if (value === null) return "NULL";
  if (typeof value === "number" && Number.isSafeInteger(value)) return String(value);
  if (typeof value === "string") return "'" + value.replaceAll("'", "''") + "'";
  throw new Error("Catalog contains a missing or invalid value");
}

const seed = rows.map((row) => {
  const values = columns.map((column) => sqlValue(row[column])).join(", ");
  const updates = columns.slice(1).map((column) => `${column} = excluded.${column}`).join(", ");
  return `INSERT INTO global_bounties (${columns.join(", ")}) VALUES (${values})
ON CONFLICT(id) DO UPDATE SET ${updates} WHERE excluded.checked_on > global_bounties.checked_on;`;
});
const schemaStatements = schema.trim().split(/;\s*/).filter(Boolean);

await mkdir(new URL("dist/", import.meta.url), { recursive: true });
await writeFile(new URL("dist/worker.js", import.meta.url),
  `const bootstrapSql = ${JSON.stringify([...schemaStatements, ...seed])};\n` +
  `const openApiDocument = ${JSON.stringify(JSON.parse(openapi))};\n` +
  `const civicWork = ${JSON.stringify(civicWork)};\n` + worker
);
const seedSql = "-- Generated by build.js from catalog.json.\n" + seed.join("\n\n") + "\n";
const seedPath = new URL("seed.sql", import.meta.url);
if (process.argv.includes("--write-seed")) {
  await writeFile(seedPath, seedSql);
} else if (await read("seed.sql") !== seedSql) {
  throw new Error("seed.sql differs from catalog.json. Run node build.js --write-seed");
}
